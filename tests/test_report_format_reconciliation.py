@pytest.mark.parametrize(
    "corrupt", ["conservation", "observed", "boolean", "status", "count", "unparsed"]
)
def test_host_refuses_inconsistent_fresh_execution_totals(corrupt):
    from test_receipt_assessor import ContainerFS

    from sag.agent.receipt_test_rows import read_delta_testcase_rows

    path = "/workspace/proj/target/surefire-reports/TEST-a.xml"
    container = ContainerFS(files={path: JUNIT})
    original = container._exact_row_read

    def corrupt_read(tokens):
        result = original(tokens)
        payload = json.loads(result["output"])
        totals = payload["execution_totals"]
        if corrupt == "conservation":
            totals["passed"] = 0
        elif corrupt == "observed":
            totals.update(passed=2, reported=2)
        elif corrupt == "boolean":
            totals["reported"] = True
        elif corrupt == "status":
            payload["status"] = "unavailable"
        elif corrupt == "count":
            payload["report_count"] = 0
        else:
            payload["bounds"]["unparsed_reports"] = 1
        result["output"] = json.dumps(payload)
        return result

    container._exact_row_read = corrupt_read
    parsed = read_delta_testcase_rows(
        container.execute_command,
        receipt_id="inv-maven-test-0001",
        delta={"new": [{"path": path, "sha256": hashlib.sha256(JUNIT.encode()).hexdigest()}]},
    )
    assert parsed["status"] == "unavailable"
    assert parsed["reasons"] == ["execution_totals_inconsistent"]
